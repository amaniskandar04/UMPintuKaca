import fs from "node:fs";
import path from "node:path";
import { places as curatedPlaces } from "../data/campus/curated.mjs";

const ROOT = process.cwd();
const DATA_DIR = path.join(ROOT, "data", "campus");
const OUTPUT_JSON = path.join(ROOT, "data", "um_places.json");
const OUTPUT_RAW = path.join(ROOT, "data", "um_places_raw.json");
const OUTPUT_CSV = path.join(ROOT, "data", "um_places.csv");
const OUTPUT_REPORT = path.join(ROOT, "data", "um_places_report.json");
const OUTPUT_SQL = path.join(ROOT, "apps", "api", "seed", "places.seed.sql");
const LAST_VERIFIED = "2026-11-25";
const CREATED_AT = "2026-11-25T00:00:00.000Z";

function ensureDir(dir) {
  fs.mkdirSync(dir, { recursive: true });
}

function slugify(value) {
  return String(value)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "");
}

function sqlString(value) {
  if (value === null || value === undefined || value === "") return "NULL";
  return `'${String(value).replace(/'/g, "''")}'`;
}

function csvCell(value) {
  const text = value === null || value === undefined ? "" : String(value);
  return `"${text.replace(/"/g, '""')}"`;
}

function buildCurated() {
  const usedCodes = new Set();
  return curatedPlaces.map((place) => {
    let code = String(place.code).toUpperCase().replace(/[^A-Z0-9-]/g, "-").replace(/-+/g, "-").replace(/^-+|-+$/g, "");
    if (!code) code = "PLACE";
    let unique = code;
    let suffix = 2;
    while (usedCodes.has(unique)) {
      unique = `${code}-${suffix}`;
      suffix += 1;
    }
    usedCodes.add(unique);
    return {
      ...place,
      code: unique,
      id: `ent_place_${slugify(unique)}`,
      aliases: [...new Set(place.aliases ?? [])],
      sourceUrls: [...new Set(place.sourceUrls ?? [])],
      lastVerified: place.lastVerified ?? LAST_VERIFIED,
      confidence: place.confidence ?? "high",
      active: place.active !== false && place.confidence !== "low"
    };
  });
}

function writeCsv(places, filePath) {
  const header = ["code", "name", "kind", "category", "location", "openingHours", "phone", "email", "confidence", "active", "sourceUrls"];
  const lines = [header.join(",")];
  for (const place of places) {
    lines.push(
      [
        csvCell(place.code),
        csvCell(place.name),
        csvCell(place.kind),
        csvCell(place.category),
        csvCell(place.location),
        csvCell(place.openingHours),
        csvCell(place.phone),
        csvCell(place.email),
        csvCell(place.confidence),
        csvCell(place.active ? "1" : "0"),
        csvCell(place.sourceUrls.join("; "))
      ].join(",")
    );
  }
  fs.writeFileSync(filePath, `${lines.join("\n")}\n`, "utf8");
}

function writeSql(places, filePath) {
  const lines = [
    "-- Generated by scripts/mine-campus.mjs from data/campus/curated.mjs. Do not edit by hand.",
    `-- Generated at ${new Date().toISOString()}. Source data: data/um_places.json.`,
    "",
    "DELETE FROM entities WHERE type = 'place';",
    "",
    "INSERT OR IGNORE INTO entities (id, type, code, name, faculty, category, description, metadata_json, active, created_at) VALUES"
  ];
  const rows = places.map((place) => {
    const metadata = JSON.stringify({
      kind: place.kind,
      location: place.location,
      openingHours: place.openingHours ?? null,
      access: place.access ?? null,
      bookingRequired: place.bookingRequired ?? null,
      bookingUrl: place.bookingUrl ?? null,
      cost: place.cost ?? null,
      phone: place.phone ?? null,
      email: place.email ?? null,
      tags: place.tags ?? [],
      coordinates: place.coordinates ?? null,
      confidence: place.confidence,
      sources: ["campus-curated-2026"],
      sourceUrls: place.sourceUrls,
      lastVerified: place.lastVerified
    });
    return `  (${sqlString(place.id)}, 'place', ${sqlString(place.code)}, ${sqlString(place.name)}, NULL, ${sqlString(place.category)}, ${sqlString(place.description)}, ${sqlString(metadata)}, ${place.active ? 1 : 0}, ${sqlString(CREATED_AT)})`;
  });
  lines.push(`${rows.join(",\n")};`);
  lines.push("");
  fs.writeFileSync(filePath, `${lines.join("\n")}\n`, "utf8");
}

function main() {
  const places = buildCurated();
  const report = {
    generatedAt: new Date().toISOString(),
    lastVerified: LAST_VERIFIED,
    total: places.length,
    byCategory: {},
    byKind: {},
    source: "data/campus/curated.mjs",
    duplicates: []
  };

  const seen = new Set();
  for (const place of places) {
    if (seen.has(place.code)) report.duplicates.push(place.code);
    seen.add(place.code);
    report.byCategory[place.category] = (report.byCategory[place.category] ?? 0) + 1;
    report.byKind[place.kind] = (report.byKind[place.kind] ?? 0) + 1;
  }

  const raw = {
    generatedAt: report.generatedAt,
    lastVerified: report.lastVerified,
    curated: places
  };

  ensureDir(DATA_DIR);
  ensureDir(path.dirname(OUTPUT_SQL));
  fs.writeFileSync(OUTPUT_JSON, `${JSON.stringify({ generatedAt: report.generatedAt, lastVerified: report.lastVerified, places }, null, 2)}\n`, "utf8");
  fs.writeFileSync(OUTPUT_RAW, `${JSON.stringify(raw, null, 2)}\n`, "utf8");
  fs.writeFileSync(OUTPUT_REPORT, `${JSON.stringify(report, null, 2)}\n`, "utf8");
  writeCsv(places, OUTPUT_CSV);
  writeSql(places, OUTPUT_SQL);

  console.log(`Places: ${places.length}`);
  console.log(`Categories: ${JSON.stringify(report.byCategory)}`);
  console.log(`Kinds: ${JSON.stringify(report.byKind)}`);
  console.log(`Duplicate codes: ${report.duplicates.length}`);
  console.log(`Wrote ${path.relative(ROOT, OUTPUT_JSON)}`);
  console.log(`Wrote ${path.relative(ROOT, OUTPUT_CSV)}`);
  console.log(`Wrote ${path.relative(ROOT, OUTPUT_REPORT)}`);
  console.log(`Wrote ${path.relative(ROOT, OUTPUT_SQL)}`);
}

main();
