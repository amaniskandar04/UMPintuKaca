import rawIndex from "../data/courses.generated.json";

/**
 * The course catalogue, bundled with the Worker.
 *
 * Search used to load the whole `courses` table out of D1 for every request
 * because relevance ranking happens in JavaScript. At ~4.6k rows per search
 * that exhausted the D1 free tier quickly, and any row cap silently made
 * courses unsearchable. The catalogue is static between scrapes, so it ships
 * as a generated module instead and only the small set of matched results
 * touches the database (to fetch review aggregates).
 *
 * Regenerate with:
 *   node scripts/build-course-seed.mjs \
 *     --subjects=data/um_s1_2026_2027_subjects_events.json,data/um_s2_2025_2026_subjects_events.json \
 *     --index=apps/api/src/data/courses.generated.json --index-only
 */
interface RawCourseIndex {
  version: number;
  generatedAt: string;
  count: number;
  faculties: string[];
  courses: [string, string, number, string | null, number | null][];
}

import { normalizeSearchText } from "./search";

export interface CourseEntry {
  id: string;
  code: string;
  name: string;
  faculty: string;
  department: string | null;
  credits: number | null;
  /** Pre-normalised search text, computed once per isolate. */
  normCode: string;
  normName: string;
  normFaculty: string;
  normDepartment: string | null;
}

const raw = rawIndex as unknown as RawCourseIndex;

/** Matches the id generated by scripts/build-course-seed.mjs. */
export function courseId(code: string): string {
  return `crs_${code.toLowerCase().replace(/[^a-z0-9]+/g, "_")}`;
}

/** Mirrors `canonicalFacultySql` in db/queries.ts so filters match exactly. */
function canonicalFaculty(value: string): string {
  const upper = value.trim().toUpperCase();
  if (upper === "FACULTY OF SPORTS AND EXERCISE SCIENCE") return "FACULTY OF SPORTS AND EXERCISE SCIENCES";
  if (upper === "UMCCED") return "UNIVERSITI MALAYA CENTRE FOR CONTINUING EDUCATION (UMCCED)";
  return upper;
}

// Faculty names are long and repeat across thousands of rows, so canonicalise
// and normalise the 22 distinct values once instead of once per course.
const canonicalFaculties = raw.faculties.map(canonicalFaculty);
const normalizedFaculties = canonicalFaculties.map((faculty) => normalizeSearchText(faculty));

// Department codes are a few hundred distinct values; memoise to keep the
// one-off build cheap.
const normalizedDepartments = new Map<string, string>();

function normalizeDepartment(value: string | null): string | null {
  if (!value) return null;
  const cached = normalizedDepartments.get(value);
  if (cached !== undefined) return cached;
  const normalized = normalizeSearchText(value);
  normalizedDepartments.set(value, normalized);
  return normalized;
}

export const COURSE_INDEX: CourseEntry[] = raw.courses.map(([code, name, facultyIndex, department, credits]) => ({
  id: courseId(code),
  code,
  name,
  faculty: canonicalFaculties[facultyIndex] ?? "UNIVERSITY",
  department,
  credits,
  normCode: normalizeSearchText(code),
  normName: normalizeSearchText(name),
  normFaculty: normalizedFaculties[facultyIndex] ?? "",
  normDepartment: normalizeDepartment(department)
}));

export const COURSE_INDEX_META = {
  version: raw.version,
  generatedAt: raw.generatedAt,
  count: COURSE_INDEX.length
} as const;
